def expand_swap_num_zones(lines: list[str], zones51: set[str]) -> list[str]:
    pattern = re.compile(
        r'^(\s*)num_zones\s*=\s*\{\s*type\s*=\s*(zone_pd_[a-z0-9_]+)\s+value\s*>\s*0\s*\}\s*$'
    )
    out: list[str] = []
    for line in lines:
        m = pattern.match(line)
        if m and m.group(2) in zones51:
            indent, zid = m.groups()
            out.append(f"{indent}OR = {{")
            out.append(f"{indent}\tnum_zones = {{ type = {zid} value > 0 }}")
            out.append(f"{indent}\tnum_zones = {{ type = {zid}_wilderness value > 0 }}")
            out.append(f"{indent}}}")
        else:
            out.append(line)
    return out


def gate_swap_trigger(lines: list[str], gate: str) -> list[str]:
    for i, line in enumerate(lines):
        if re.match(r'^\s*trigger\s*=\s*\{', line):
            lines.insert(i + 1, f"{indent_of(line)}\t{gate}")
            return lines
    raise ValueError("swap_type has no trigger block")


def rename_swap_line(lines: list[str], pattern: str, content: str) -> list[str]:
    """Replace exactly one matching line, keeping its original indentation."""
    regex = re.compile(pattern)
    hits = [i for i, line in enumerate(lines) if regex.match(line)]
    if len(hits) != 1:
        raise ValueError(f"Expected exactly one line matching {pattern}, found {len(hits)}")
    lines[hits[0]] = indent_of(lines[hits[0]]) + content
    return lines


def make_wilderness_swap(block: list[str], job_id: str) -> list[str]:
    """Duplicate an already-expanded PD swap entry and retarget it at the Wilderness job."""
    wild = gate_swap_trigger(list(block), SWAP_GATE_YES)
    wild = rename_swap_line(
        wild,
        r'^\s*name\s*=\s*' + re.escape(job_id) + r'\s*$',
        f"name = {job_id}_wilderness",
    )
    wild = rename_swap_line(
        wild,
        r'^\s*desc\s*=\s*job_' + re.escape(job_id) + r'_desc\s*$',
        f"desc = job_{job_id}_wilderness_desc",
    )
    wild = rename_swap_line(wild, r'^\s*weight\s*=\s*\d+\s*$', "weight = 300")
    return wild


def generate_swap_file(filename: str, zones: list[dict]) -> tuple[int, int]:
    source = PD / "common/pop_jobs" / filename
    lines = read_lines(source)
    zones51 = {z["zone"] for z in zones}
    job_ids = {z["job"] for z in zones}

    swap_pattern = re.compile(r'^\s*swap_type\s*=\s*\{')
    blocks: list[tuple[int, int, list[str]]] = []
    i = 0
    while i < len(lines):
        if swap_pattern.match(lines[i]):
            end = find_block_end(lines, i)
            blocks.append((i, end, lines[i : end + 1]))
            i = end + 1
        else:
            i += 1

    out: list[str] = [
        f"# Wilderness split generated by tools/generate_wilderness_split.py from Planetary Diversity's {filename}.",
        "# The original PD swap entries are gated to non-Wilderness empires. The appended",
        "# entries use the new _drone_wilderness job IDs and only apply to Wilderness empires.",
        "",
    ]
    cursor = 0
    originals = 0
    duplicates = 0
    for start, end, block in blocks:
        # Keep everything before the block (including comments).
        out.extend(lines[cursor:start])
        cursor = end + 1

        name_line = next(
            (l for l in block if re.match(r'^\s*name\s*=\s*[a-z0-9_]+\s*$', l)), None
        )
        name = None
        if name_line:
            name = re.match(r'^\s*name\s*=\s*([a-z0-9_]+)\s*$', name_line).group(1)

        if name not in job_ids:
            out.extend(block)
            continue

        base = expand_swap_num_zones(list(block), zones51)
        original = gate_swap_trigger(list(base), SWAP_GATE_NO)
        wild = make_wilderness_swap(base, name)
        assert_balanced(original, f"{filename}:{name}")
        assert_balanced(wild, f"{filename}:{name}_wilderness")

        out.extend(original)
        out.extend(wild)
        originals += 1
        duplicates += 1

    out.extend(lines[cursor:])
    assert_balanced(out, filename)
    write_text(SWAP_OUT_DIR / filename, join_lines(out))
    return originals, duplicates


