#!/usr/bin/env python3
"""
Planetary Diversity x Wilderness - zone/job split generator.

What this script does
---------------------
Planetary Diversity's rare/uncommon specialization zones and their drone jobs
are shared by every empire. Stellaris localisation cannot be made conditional
on a country trigger, so the only way to give Wilderness empires their own
visible zone and job names is to duplicate the content:

  * every one of the 51 supported zones gets a second zone ID
    `zone_pd_*_wilderness`, gated to Wilderness empires;
  * the original `zone_pd_*` is gated to non-Wilderness empires;
  * every sibling `num_zones` check counts both IDs, so the "one of three"
    rule still holds after a conquest or a save upgrade;
  * every one of the 51 jobs gets a `pd_*_drone_wilderness` stub and a
    dedicated job swap entry that only applies to Wilderness empires;
  * the original PD job swaps are gated to non-Wilderness empires;
  * new game concepts and localisation keys point at the new IDs.

The guild/resort zones (12 of them) are intentionally left alone: they stay
closed to Wilderness through their existing `is_gestalt = no` /
`country_uses_consumer_goods = yes` requirements, and they keep their original
PD names.

Inputs
------
  tools/pd_wilderness_names.json   human-editable names for the 51 entries
  PlanetaryDiveristy-main/...      PD source of truth (zones, jobs, swaps,
                                   concepts, localisation)

Outputs (all inside pd_wilderness_compat)
-----------------------------------------
  common/zones/zzz_pd_wilderness_rare_zones.txt
  common/zones/zzz_pd_wilderness_uncommon_zones.txt
  common/inline_scripts/zones/pd_rare_zone_common_nonwilderness.txt
  common/inline_scripts/zones/pd_rare_zone_common_wilderness.txt
  common/game_concepts/zzz_pd_wilderness_concepts.txt
  common/pop_jobs/zzz_pd_wilderness_jobs.txt
  common/pop_jobs/zzz_pd_{agri,calculator_*,fabricator,mining,technician}_drone.txt
  localisation/{english,spanish}/zzz_pd_wilderness_names_l_*.yml

The script is idempotent: it removes its own generated gates, sibling checks
and `_wilderness` blocks before regenerating them.
"""

