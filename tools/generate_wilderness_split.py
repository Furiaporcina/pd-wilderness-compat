# ---------------------------------------------------------------------------
# Small text helpers
# ---------------------------------------------------------------------------


def read_lines(path: Path) -> list[str]:
    """Read a text file as LF lines without a trailing empty element."""
    text = path.read_text(encoding="utf-8-sig")
    return text.replace("\r\n", "\n").replace("\r", "\n").split("\n")


def write_text(path: Path, text: str, *, bom: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    encoding = "utf-8-sig" if bom else "utf-8"
    with open(path, "w", encoding=encoding, newline="\n") as fh:
        fh.write(text)


def join_lines(lines: list[str]) -> str:
    # Drop a single trailing empty line so we can always add exactly one.
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def strip_comment(line: str) -> str:
    out: list[str] = []
    in_quotes = False
    for ch in line:
        if ch == '"':
            in_quotes = not in_quotes
        if ch == "#" and not in_quotes:
            break
        out.append(ch)
    return "".join(out)


def brace_delta(line: str) -> int:
    clean = strip_comment(line)
    return clean.count("{") - clean.count("}")


def indent_of(line: str) -> str:
    return line[: len(line) - len(line.lstrip(" \t"))]


def find_block_end(lines: list[str], start: int) -> int:
    depth = 0
    for i in range(start, len(lines)):
        depth += brace_delta(lines[i])
        if depth == 0:
            return i
    raise ValueError(f"Unbalanced block starting at line {start + 1}: {lines[start]!r}")


def split_top_level_blocks(lines: list[str], key_re: str) -> list[tuple[str, int, int, list[str]]]:
    """Return (key, start, end, block_lines) for top-level `key = { ... }` blocks."""
    pattern = re.compile(key_re)
    result: list[tuple[str, int, int, list[str]]] = []
    i = 0
    while i < len(lines):
        m = pattern.match(lines[i])
        if not m:
            i += 1
            continue
        end = find_block_end(lines, i)
        result.append((m.group(1), i, end, lines[i : end + 1]))
        i = end + 1
    return result


def parse_loc(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in read_lines(path):
        m = re.match(r'^\s*([A-Za-z0-9_]+):\s*"(.*)"\s*$', line)
        if m:
            values[m.group(1)] = m.group(2)
    return values


def assert_balanced(lines: list[str], label: str) -> None:
    depth = 0
    for n, line in enumerate(lines, 1):
        depth += brace_delta(line)
        if depth < 0:
            raise ValueError(f"{label}: negative brace depth at line {n}: {line!r}")
    if depth != 0:
        raise ValueError(f"{label}: unbalanced braces (depth {depth})")


# ---------------------------------------------------------------------------
# Zone helpers
# ---------------------------------------------------------------------------


def expand_zone_num_zones(lines: list[str], zones: set[str]) -> list[str]:
    pattern = re.compile(
        r'^(\s*)num_zones\s*=\s*\{\s*type\s*=\s*(zone_pd_[a-z0-9_]+)\s+(value\s*=\s*0)\s*\}\s*$'
    )
    out: list[str] = []
    for line in lines:
        m = pattern.match(line)
        if m and m.group(2) in zones:
            indent, zid, condition = m.groups()
            out.append(line)
            out.append(f"{indent}num_zones = {{ type = {zid}_wilderness {condition} }}")
        else:
            out.append(line)
    return out


def add_potential_gate(lines: list[str], gate: str) -> list[str]:
    for i, line in enumerate(lines):
        if re.match(r'^\s*potential\s*=\s*\{', line):
            lines.insert(i + 1, f"{indent_of(line)}\t{gate}")
            return lines
    raise ValueError("Zone has no potential block")


def add_unlock_gate(
    lines: list[str], gate: str, script_from: str = SCRIPT_BASE, script_to: str = SCRIPT_BASE
) -> list[str]:
    for i, line in enumerate(lines):
        if re.match(r'^\s*unlock\s*=\s*\{', line):
            lines.insert(i + 1, f"{indent_of(line)}\t{gate}")
            return lines
    for i, line in enumerate(lines):
        if re.search(r'inline_script\s*=\s*"' + re.escape(script_from) + r'"', line):
            lines[i] = line.replace(script_from, script_to)
            return lines
    raise ValueError("Zone has neither an inline unlock nor the shared zone script")


def rename_zone(lines: list[str], new_id: str) -> list[str]:
    m = re.match(r'^(zone_pd_[a-z0-9_]+)\s*=\s*\{', lines[0])
    if not m:
        raise ValueError(f"Unexpected zone header: {lines[0]!r}")
    lines[0] = re.sub(r'^zone_pd_[a-z0-9_]+', new_id, lines[0])
    return lines


def replace_wilderness_swap_desc(lines: list[str], job_base: str) -> list[str]:
    new_key = f"pd_{job_base}_wilderness_swap_tt"
    found = 0
    for i, line in enumerate(lines):
        m = re.match(r'^(\s*)text\s*=\s*pd_([a-z0-9_]+)_drone_swap_tt\s*$', line)
        if m:
            lines[i] = f"{m.group(1)}text = {new_key}"
            found += 1
    if found != 1:
        raise ValueError(f"Expected exactly one drone swap tooltip, found {found}")
    return lines


def clean_baseline(lines: list[str]) -> list[str]:
    """Undo the split so the script can be re-run without duplicating blocks."""
    # Drop the generated wilderness section, if present.
    for i, line in enumerate(lines):
        if line.strip() == MARKER:
            lines = lines[:i]
            break

    gate_re = re.compile(
        r'^\s*hidden_trigger\s*=\s*\{\s*exists\s*=\s*owner\s+owner\s*=\s*\{\s*is_wilderness_empire\s*=\s*(yes|no)\s*\}\s*\}\s*$'
    )
    wild_num_re = re.compile(
        r'^\s*num_zones\s*=\s*\{\s*type\s*=\s*zone_pd_[a-z0-9_]+_wilderness\s+value\s*=\s*0\s*\}\s*$'
    )

    out: list[str] = []
    i = 0
    while i < len(lines):
        m = re.match(r'^(zone_pd_[a-z0-9_]+)\s*=\s*\{', lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        end = find_block_end(lines, i)
        zid = m.group(1)
        block = lines[i : end + 1]
        i = end + 1
        if zid.endswith("_wilderness"):
            continue
        cleaned: list[str] = []
        for line in block:
            if gate_re.match(line):
                continue
            if wild_num_re.match(line):
                continue
            line = line.replace(SCRIPT_NONWILD, SCRIPT_BASE)
            line = line.replace(SCRIPT_WILD, SCRIPT_BASE)
            cleaned.append(line)
        out.extend(cleaned)
    return out


# ---------------------------------------------------------------------------
# Zone file generation
# ---------------------------------------------------------------------------


def generate_zone_file(
    path: Path, zones: list[dict], label: str
) -> tuple[int, int]:
    """Rewrite one zone file with gated originals and appended wilderness copies."""
    lines = clean_baseline(read_lines(path))
    zones_by_id = {z["zone"]: z for z in zones}
    zones51 = set(zones_by_id)

    blocks = split_top_level_blocks(lines, r'^(zone_pd_[a-z0-9_]+)\s*=\s*\{')
    seen = {key for key, *_ in blocks}
    unknown = {
        key
        for key in seen
        if key not in zones51 and not (key.endswith("_guild") or key.endswith("_resort"))
    }
    if unknown:
        raise ValueError(f"{label}: unexpected zones: {sorted(unknown)}")

    original_out: list[str] = []
    wilderness_out: list[str] = []
    cursor = 0

    for zid, start, end, block in blocks:
        # Preserve any comments/blank lines before the block.
        original_out.extend(lines[cursor:start])
        cursor = end + 1

        included = zid in zones_by_id
        is_guild_or_resort = zid.endswith("_guild") or zid.endswith("_resort")
        if not included and not is_guild_or_resort:
            raise ValueError(f"{label}: unexpected zone {zid}")

        base = expand_zone_num_zones(block, zones51)
        original = list(base)
        if included:
            original = add_potential_gate(original, GATE_NO)
            original = add_unlock_gate(original, GATE_NO, SCRIPT_BASE, SCRIPT_NONWILD)
        original_out.extend(original)

        if included:
            job_base = zones_by_id[zid]["job"].removeprefix("pd_").removesuffix("_drone")
            wild = expand_zone_num_zones(block, zones51)
            wild = rename_zone(wild, f"{zid}_wilderness")
            wild = add_potential_gate(wild, GATE_YES)
            wild = add_unlock_gate(wild, GATE_YES, SCRIPT_BASE, SCRIPT_WILD)
            wild = replace_wilderness_swap_desc(wild, job_base)
            wilderness_out.extend(wild)
            wilderness_out.append("")

    # Trailing comments after the last block.
    original_out.extend(lines[cursor:])

    out = original_out
    while out and out[-1] == "":
        out.pop()
    out.append("")
    out.append(MARKER)
    out.append("# Originals above are non-Wilderness only. The copies below are Wilderness only.")
    out.extend(wilderness_out)

    assert_balanced(out, label)
    write_text(path, join_lines(out))

    return len(blocks), sum(1 for z in zones if z["zone"] in seen)


