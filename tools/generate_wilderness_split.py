def generate_job_stubs(zones: list[dict]) -> int:
    job_ids = [z["job"] for z in zones]
    all_blocks: dict[str, list[str]] = {}
    for source in (PD_RARE_JOBS, PD_UNCOMMON_JOBS):
        for key, _start, _end, block in split_top_level_blocks(
            read_lines(source), r'^(pd_[a-z0-9_]+)\s*=\s*\{'
        ):
            all_blocks[key] = block

    missing = [j for j in job_ids if j not in all_blocks]
    if missing:
        raise ValueError(f"Job stubs missing from PD: {missing}")

    out = [
        "# Wilderness-only job stubs.",
        "# Generated by tools/generate_wilderness_split.py from Planetary Diversity's",
        "# pd_rare_jobs.txt / pd_uncommon_jobs.txt. Each stub is a byte-for-byte copy of",
        "# the original _drone job with a _wilderness suffix. `possible = { always = no }`",
        "# keeps the stub out of the normal job pool; the swap files assign it.",
        "",
    ]
    for job_id in job_ids:
        block = list(all_blocks[job_id])
        m = re.match(r'^(pd_[a-z0-9_]+)\s*=\s*\{', block[0])
        if not m or m.group(1) != job_id:
            raise ValueError(f"Unexpected job block header: {block[0]!r}")
        block[0] = re.sub(r'^pd_[a-z0-9_]+', f"{job_id}_wilderness", block[0])
        assert_balanced(block, f"job {job_id}")
        out.extend(block)
        out.append("")
    write_text(JOBS_OUT, join_lines(out))
    return len(job_ids)


