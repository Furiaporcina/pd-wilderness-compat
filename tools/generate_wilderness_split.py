def generate_concepts(zones: list[dict]) -> int:
    blocks = split_top_level_blocks(
        read_lines(PD_CONCEPTS), r'^(concept_zone_pd_[a-z0-9_]+)\s*=\s*\{'
    )
    by_key = {key: block for key, _s, _e, block in blocks}

    out = [
        "# Wilderness-only copies of Planetary Diversity's zone game concepts.",
        "# Generated by tools/generate_wilderness_split.py. The icon is copied from the",
        "# original concept so the new zone keeps the same district-specialization art.",
        "",
    ]
    count = 0
    for entry in zones:
        zid = entry["zone"]
        source_key = f"concept_{zid}"
        if source_key not in by_key:
            raise ValueError(f"Missing concept definition: {source_key}")
        block = list(by_key[source_key])
        m = re.match(r'^(concept_zone_pd_[a-z0-9_]+)\s*=\s*\{', block[0])
        if not m or m.group(1) != source_key:
            raise ValueError(f"Unexpected concept header: {block[0]!r}")
        block[0] = re.sub(
            r'^concept_zone_pd_[a-z0-9_]+',
            f"concept_{zid}_wilderness",
            block[0],
        )
        assert_balanced(block, source_key)
        out.extend(block)
        out.append("")
        count += 1
    write_text(CONCEPTS_OUT, join_lines(out))
    return count


