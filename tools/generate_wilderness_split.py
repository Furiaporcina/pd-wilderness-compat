    print(f"  game concepts:   {concept_count}")
    print(f"  swap entries:    {swap_originals} gated originals + {swap_duplicates} wilderness copies")
    print(f"  localisation:    {loc_en} EN keys / {loc_es} ES keys")
    return 0


