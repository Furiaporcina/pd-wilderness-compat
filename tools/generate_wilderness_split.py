def generate_loc(zones: list[dict]) -> tuple[int, int]:
    pd_en = parse_loc(PD_LOC_EN)
    pd_es = parse_loc(PD_LOC_ES)

    def build(language: str, pd_loc: dict[str, str], header: str) -> list[str]:
        out = [
            f"{header}:",
            " # Wilderness-only names for the duplicated PD zones and drone jobs.",
            " # Generated by tools/generate_wilderness_split.py from tools/pd_wilderness_names.json.",
            " # The original zone/job keys are deliberately NOT overridden here: PD keeps its",
            " # own names for every non-Wilderness empire. Only the new _wilderness IDs are named.",
            " # Zone names are exclusive to Wilderness because the original zones are gated to",
            " # non-Wilderness empires; job names are exclusive because the new job IDs are only",
            " # referenced by the Wilderness-only swap entries.",
            "",
        ]
        count = 0
        for entry in zones:
            zid = entry["zone"]                      # zone_pd_geothermal_grid
            sid = zid.removeprefix("zone_pd_")       # geothermal_grid
            job_id = entry["job"]                     # pd_geothermal_vent_tapper_drone
            job_base = job_id.removeprefix("pd_").removesuffix("_drone")
            names = entry[language]
            tt_key = f"pd_{job_base}_drone_swap_tt"
            if tt_key not in pd_loc:
                raise ValueError(f"Missing PD swap tooltip: {tt_key}")
            tt = pd_loc[tt_key]
            plural_var = f"$job_{job_id}_plural$"
            if plural_var not in tt:
                raise ValueError(f"{tt_key} does not reference {plural_var}")
            tt = tt.replace(plural_var, f"$job_{job_id}_wilderness_plural$")

            out.append(f" # {names['zone']} - {zid}")
            out.append(f' zone_pd_{sid}_wilderness: "{names["zone"]}"')
            out.append(f' zone_pd_{sid}_wilderness_desc: "$zone_pd_{sid}_desc$"')
            out.append(f' concept_zone_pd_{sid}_wilderness: "$zone_pd_{sid}_wilderness$"')
            out.append(f' concept_zone_pd_{sid}_wilderness_desc: "\u00a3L$zone_pd_{sid}_desc$\u00a3!"')
            # The swap "name" field is resolved without the job_ prefix; the plural and
            # description use the usual job_<name>_plural / job_<name>_desc keys.
            out.append(f' pd_{job_id.removeprefix("pd_")}_wilderness: "$job_{job_id}_wilderness$"')
            out.append(f' job_{job_id}_wilderness: "{names["job"]}"')
            out.append(f' job_{job_id}_wilderness_plural: "{names["plural"]}"')
            out.append(f' job_{job_id}_wilderness_desc: "$job_{job_id}_desc$"')
            out.append(f' pd_{job_base}_wilderness_swap_tt: "{tt}"')
            out.append("")
            count += 1
        return out

    en_lines = build("en", pd_en, "l_english")
    es_lines = build("es", pd_es, "l_spanish")
    write_text(LOC_EN, join_lines(en_lines), bom=True)
    write_text(LOC_ES, join_lines(es_lines), bom=True)
    return len(zones), len(zones)


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------


def validate(zones: list[dict]) -> None:
    errors: list[str] = []
    zones51 = {z["zone"] for z in zones}
    job_ids = {z["job"] for z in zones}

    # Zone files: 51 wilderness copies, 51 gated originals, all references defined.
    all_zone_defs: set[str] = set()
    wild_count = 0
    for path in (RARE_ZONES, UNCOMMON_ZONES):
        blocks = split_top_level_blocks(read_lines(path), r'^(zone_pd_[a-z0-9_]+)\s*=\s*\{')
        for key, _s, _e, block in blocks:
            if key in all_zone_defs:
                errors.append(f"duplicate zone definition: {key}")
            all_zone_defs.add(key)
            if key.endswith("_wilderness"):
                wild_count += 1
    if wild_count != 51:
        errors.append(f"expected 51 wilderness zones, found {wild_count}")
    if len(all_zone_defs) != 114:
        errors.append(f"expected 114 zone definitions, found {len(all_zone_defs)}")

    # Every num_zones reference resolves.
    ref_re = re.compile(r'num_zones\s*=\s*\{\s*type\s*=\s*(zone_pd_[a-z0-9_]+)')
    for path in (RARE_ZONES, UNCOMMON_ZONES):
        for line in read_lines(path):
            for m in ref_re.finditer(line):
                if m.group(1) not in all_zone_defs:
                    errors.append(f"{path.name}: unresolved num_zones type {m.group(1)}")

    # Job stubs.
    job_blocks = split_top_level_blocks(read_lines(JOBS_OUT), r'^(pd_[a-z0-9_]+)\s*=\s*\{')
    job_keys = {key for key, *_ in job_blocks}
    expected_job_keys = {f"{j}_wilderness" for j in job_ids}
    if job_keys != expected_job_keys:
        errors.append(f"job stub keys mismatch: missing={expected_job_keys - job_keys} extra={job_keys - expected_job_keys}")

    # Concepts.
    concept_blocks = split_top_level_blocks(
        read_lines(CONCEPTS_OUT), r'^(concept_zone_pd_[a-z0-9_]+)\s*=\s*\{'
    )
    concept_keys = {key for key, *_ in concept_blocks}
    expected_concepts = {f"concept_{z['zone']}_wilderness" for z in zones}
    if concept_keys != expected_concepts:
        errors.append("concept keys mismatch")

    # Swaps: 51 wilderness entries across the seven files.
    wild_swap_count = 0
    for filename in SWAP_FILES:
        text = (SWAP_OUT_DIR / filename).read_text(encoding="utf-8")
        if f"# {filename}" not in text and filename not in text:
            errors.append(f"{filename}: missing generated header")
        wild_swap_count += len(re.findall(r'^\s*name\s*=\s*pd_[a-z0-9_]+_drone_wilderness\s*$', text, re.M))
        # The original entries must be gated to non-Wilderness.
        if "is_wilderness_empire = no" not in text:
            errors.append(f"{filename}: original swaps are not gated")
    if wild_swap_count != 51:
        errors.append(f"expected 51 wilderness swap entries, found {wild_swap_count}")

    # Localisation: 9 keys per entry, no duplicates, no original overrides.
    for path, lang in ((LOC_EN, "en"), (LOC_ES, "es")):
        values = parse_loc(path)
        if len(values) != 459:
            errors.append(f"{path.name}: expected 459 keys, found {len(values)}")
        expected = set()
        for entry in zones:
            zid = entry["zone"]
            job_id = entry["job"]
            job_base = job_id.removeprefix("pd_").removesuffix("_drone")
            expected |= {
                f"zone_pd_{zid.removeprefix('zone_pd_')}_wilderness",
                f"zone_pd_{zid.removeprefix('zone_pd_')}_wilderness_desc",
                f"concept_zone_pd_{zid.removeprefix('zone_pd_')}_wilderness",
                f"concept_zone_pd_{zid.removeprefix('zone_pd_')}_wilderness_desc",
                f"pd_{job_id.removeprefix('pd_')}_wilderness",
                f"job_{job_id}_wilderness",
                f"job_{job_id}_wilderness_plural",
                f"job_{job_id}_wilderness_desc",
                f"pd_{job_base}_wilderness_swap_tt",
            }
        if set(values) != expected:
            errors.append(
                f"{path.name}: key set mismatch (missing={len(expected - set(values))}, extra={len(set(values) - expected)})"
            )
        # Must not override the original keys.
        for entry in zones:
            for key in (entry["zone"], entry["job"]):
                if key in values:
                    errors.append(f"{path.name}: overrides original key {key}")

    if errors:
        print("VALIDATION FAILED")
        for error in errors:
            print(" -", error)
        raise SystemExit(1)


