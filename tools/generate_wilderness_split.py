def make_inline_variant(destination: Path, gate: str) -> None:
    lines = read_lines(INLINE_BASE)
    for i, line in enumerate(lines):
        if re.match(r'^\s*unlock\s*=\s*\{', line):
            lines.insert(i + 1, f"{indent_of(line)}\t{gate}")
            break
    else:
        raise ValueError(f"No unlock block in {INLINE_BASE}")
    assert_balanced(lines, destination.name)
    write_text(destination, join_lines(lines))


